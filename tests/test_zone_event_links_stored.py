"""Stored-data regression for zone/event linkage, retest references and zone evolution.

Every candle in this file is generated by the repository's own Support & Resistance
demonstration seeder (``scripts/seed_sr_demo.py``): a deterministic 1-minute price path
aggregated to 4h candles. It is **stored synthetic test data**, explicitly not market
history, and it is inserted into a real migrated SQLite database so the whole chain —
repository, market structure, zone clustering, pattern detection, chart projection and
the read-only linkage — runs exactly as it does in the dashboard.

What is pinned here (all measured from detector output, not hand-built payloads):

* a retest records the reference band it was measured against (BRAIN-AUDIT-0005);
* at an event's own detection instant its band matches that reference **exactly**;
* at a later instant the same level has evolved, so the reference is reported as a
  **contained** earlier band — never as identity, and never as an absolute "no stored
  event used this zone";
* a band no stored event ever referenced reports neither fact (true negative);
* every reported record keeps its own stored bounds and an instant not after ``as_of``.
"""

from __future__ import annotations

from dataclasses import replace
from datetime import UTC, datetime

import pytest
from web_fixtures import insert_candles, make_settings, migrated_engine

from scripts import seed_sr_demo
from trading_assistant.market_data.types import Candle
from trading_assistant.web.dashboard_service import DashboardService
from trading_assistant.web.state import AppState

SYMBOL = "BTC/USDT"
TIMEFRAME = "4h"
#: The demo story's own span, started on a fixed 1d boundary so timestamps are stable.
DAYS = 60
START = datetime(2026, 8, 15, tzinfo=UTC)
#: The instant the demo story's `85958.6 – 86543.0` level was broken (measured).
BREAKOUT_AS_OF = datetime(2026, 8, 26, 8, 0, tzinfo=UTC)
#: The demo story's final stored boundary (measured).
LATEST_AS_OF = datetime(2026, 10, 14, 0, 0, tzinfo=UTC)


def _four_hour_candles() -> tuple[Candle, ...]:
    """The demo seeder's own 4h candles, deterministic and database-ready."""

    prices = seed_sr_demo.build_minute_path(DAYS * 24 * 60, wobble=12.0)
    rows = seed_sr_demo.aggregate(prices, 240, START)
    return tuple(replace(row, timeframe=TIMEFRAME) for row in rows)


@pytest.fixture(scope="module")
def stored_demo(tmp_path_factory):
    """One migrated database holding the stored 4h demo series, plus a service over it."""

    tmp_path = tmp_path_factory.mktemp("zone-links")
    engine, url = migrated_engine(tmp_path, "zone-links.sqlite3")
    candles = _four_hour_candles()
    assert len(candles) == 360  # 60 days of 4h candles, none invented at read time
    insert_candles(engine, candles)
    settings = make_settings(url)
    state = AppState(engine, settings=settings, clock=lambda: LATEST_AS_OF)
    try:
        yield DashboardService(state)
    finally:
        engine.dispose()


def _bands(service: DashboardService, as_of: datetime) -> list[dict]:
    dashboard = service.dashboard(symbol=SYMBOL, timeframe=TIMEFRAME, as_of=as_of)
    return (dashboard.get("overlays") or {}).get("zone_bands", {}).get("bands") or []


def _band_bounds(band: dict) -> tuple[str, str]:
    return (str(band["band_low"]), str(band["band_high"]))


def test_the_stored_demo_series_has_the_events_this_regression_needs(stored_demo):
    """Guard: the fixture must really contain zone-referenced events and retests."""

    dashboard = stored_demo.dashboard(symbol=SYMBOL, timeframe=TIMEFRAME, as_of=LATEST_AS_OF)
    evidence = dashboard["chart_evidence"]
    retests = evidence["retests"]
    assert retests, "the stored series must contain retests, or the linkage regression is vacuous"
    # BRAIN-AUDIT-0005: the projection the linkage consumes must carry the reference.
    assert all("reference_type" in item for item in retests)
    assert any(item["reference_type"] == "zone" for item in retests)
    assert any(item.get("reference_id") for item in retests)
    assert any(item["reference_type"] == "zone" for item in evidence["breakouts"])


def test_at_its_own_instant_the_reference_is_an_exact_band_link(stored_demo):
    """Positive control: identity is reported when the frame's zone is the recorded band."""

    bands = _bands(stored_demo, BREAKOUT_AS_OF)
    exact = [band for band in bands if band["linked_events"]["linked"]]
    assert exact, "the breakout's own instant must link its exact stored band"
    (band,) = exact
    assert _band_bounds(band) == ("85958.6", "86543.0")
    linkage = band["linked_events"]
    assert linkage["event_count"] == 1
    assert linkage["counts"]["breakout"] == 1
    record = linkage["events"][0]
    assert record["match"] == "exact"
    assert (record["band_low"], record["band_high"]) == ("85958.6", "86543.0")
    assert record["known_at"] == "2026-08-26T08:00:00Z"
    assert linkage["contained_note"] is None


def test_the_same_level_later_reports_the_earlier_band_as_contained_not_identical(stored_demo):
    """Historical zone evolution: bounds grow, so identity stops matching and must be said."""

    bands = _bands(stored_demo, LATEST_AS_OF)
    assert not any(band["linked_events"]["linked"] for band in bands), (
        "the evolved fixture must not claim identity it no longer has"
    )
    evolved = {_band_bounds(band): band["linked_events"] for band in bands}
    (bounds, linkage), = [
        (key, value) for key, value in evolved.items() if key == ("85958.6", "87052.5")
    ]
    assert linkage["linked"] is False
    assert linkage["event_count"] == 0
    assert linkage["events"] == []
    # The earlier, smaller recorded bands are still reported — with their own bounds.
    assert linkage["contained_count"] >= 1
    assert linkage["contained_counts"]["retest"] >= 1, (
        "retests must reach the linkage once the projection carries their reference"
    )
    assert any(item["kind"] == "breakout" for item in linkage["contained_events"])
    for record in linkage["contained_events"]:
        assert record["match"] == "contained"
        assert (record["band_low"], record["band_high"]) != bounds
        assert record["linked_via_bounds"] == {"band_low": "85958.6", "band_high": "87052.5"}
    # The identity note may stand, but it is qualified rather than absolute.
    assert linkage["contained_note"] is not None
    assert "smaller recorded references" in linkage["contained_note"]


def test_a_band_no_stored_event_referenced_reports_neither_fact(stored_demo):
    """True negative: no link and no contained reference, stated explicitly."""

    bands = {_band_bounds(band): band["linked_events"] for band in _bands(stored_demo, LATEST_AS_OF)}
    linkage = bands[("85158.0", "85158.0")]
    assert linkage["linked"] is False
    assert linkage["event_count"] == 0
    assert linkage["contained_count"] == 0
    assert linkage["contained_events"] == []
    assert linkage["contained_note"] is None
    assert linkage["note"] == "no stored event used this zone as its own reference level"


def test_every_reported_record_respects_causality_and_keeps_its_instants(stored_demo):
    """Timestamps: nothing reported may be knowable after the analysed instant."""

    reported = 0
    for as_of in (BREAKOUT_AS_OF, LATEST_AS_OF):
        for band in _bands(stored_demo, as_of):
            linkage = band["linked_events"]
            records = list(linkage["events"]) + list(linkage["contained_events"])
            reported += len(records)
            for record in records:
                assert record["known_at"] is not None
                known_at = datetime.fromisoformat(record["known_at"].replace("Z", "+00:00"))
                assert known_at <= as_of
                assert record["time"] is not None and record["time_ms"] is not None
                assert record["reference_type"] == "zone"
                assert record["reference_id"]
                # A reported event carries the close its own detector recorded, and the
                # band's position at that instant is read from it — never left unexplained.
                assert record["close_at_event"] is not None
                assert record["position_at_event"] in {"above_price", "below_price", "price_inside"}
                # The record's own bounds are the ones its detectors recorded.
                assert record["band_low"] is not None and record["band_high"] is not None
    # Both instants together must really exercise the reported paths.
    assert reported >= 10
